#!/bin/sh

set -e

root_dir=$(cd $(dirname $0); pwd)
cd $root_dir

mkdir -p build; cd build

[ -z "$J" ] && J=$(nproc | awk '{print int(($0 + 1)/ 2)}')
CMAKE=${CMAKE:-"cmake"}
CMAKE_OPTIONS=${CMAKE_OPTIONS:-""}
CMAKE_OPTIONS="$CMAKE_OPTIONS -DDLSYM_HOOK_ENABLE=1"
CMAKE_OPTIONS="$CMAKE_OPTIONS -DMULTIPROCESS_LIMIT_ENABLE=1"
CMAKE_OPTIONS="$CMAKE_OPTIONS -DHOOK_MEMINFO_ENABLE=1"
CMAKE_OPTIONS="$CMAKE_OPTIONS -DHOOK_NVML_ENABLE=1"
CMAKE_OPTIONS="$CMAKE_OPTIONS -DCMAKE_BUILD_TYPE=Debug"


${CMAKE} .. ${CMAKE_OPTIONS} -DTEST_DEVICE_ID=0
make -j$J
